using DebtManager.Application;
using DebtManager.Infrastructure;
using DebtManager.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

var builder = WebApplication.CreateBuilder(args);

// Add services to the container.
builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(c =>
{
    c.SwaggerDoc("v1", new Microsoft.OpenApi.Models.OpenApiInfo
    {
        Title = "Debt Manager API",
        Version = "v1",
        Description = "API Quản lý Bán hàng, Kho hàng đa điểm, Công nợ và Thu chi (.NET 8 Clean Architecture)"
    });
});

// Configure CORS
builder.Services.AddCors(opts =>
{
    opts.AddDefaultPolicy(p =>
    {
        p.AllowAnyHeader()
         .AllowAnyMethod()
         .AllowCredentials()
         .SetIsOriginAllowed(_ => true);
    });
});

// Add Clean Architecture Services
builder.Services.AddInfrastructureServices(builder.Configuration);
builder.Services.AddApplicationServices();
builder.Services.AddHostedService<DebtManager.Api.Services.ExportBackgroundWorker>();

var app = builder.Build();

// Ensure Database is created on startup
using (var scope = app.Services.CreateScope())
{
    var logger = scope.ServiceProvider.GetRequiredService<ILogger<Program>>();
    try
    {
        var db = scope.ServiceProvider.GetRequiredService<DebtManagerDbContext>();
        logger.LogInformation("Ensuring database is created...");
        await db.Database.EnsureCreatedAsync();

        // Ensure Employees table and ExportVouchers Employee columns exist for existing databases
        var provider = db.Database.ProviderName ?? string.Empty;
        if (provider.Contains("Npgsql", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync(@"
                CREATE TABLE IF NOT EXISTS ""Employees"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""Name"" character varying(200) NOT NULL,
                    ""Phone"" character varying(50) NULL,
                    ""Notes"" character varying(500) NULL,
                    ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT NOW()
                );
                CREATE TABLE IF NOT EXISTS ""CustomerWarehouseDebts"" (
                    ""Id"" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""CustomerId"" integer NOT NULL REFERENCES ""Customers""(""Id"") ON DELETE CASCADE,
                    ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1',
                    ""Debt"" numeric(18,2) NOT NULL DEFAULT 0,
                    ""UpdatedAt"" timestamp with time zone NOT NULL DEFAULT NOW()
                );
                CREATE UNIQUE INDEX IF NOT EXISTS ""IX_CustomerWarehouseDebts_CustomerId_Warehouse"" ON ""CustomerWarehouseDebts"" (""CustomerId"", ""Warehouse"");

                CREATE TABLE IF NOT EXISTS ""SupplierWarehouseDebts"" (
                    ""Id"" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""SupplierId"" integer NOT NULL REFERENCES ""Suppliers""(""Id"") ON DELETE CASCADE,
                    ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1',
                    ""Debt"" numeric(18,2) NOT NULL DEFAULT 0,
                    ""UpdatedAt"" timestamp with time zone NOT NULL DEFAULT NOW()
                );
                CREATE UNIQUE INDEX IF NOT EXISTS ""IX_SupplierWarehouseDebts_SupplierId_Warehouse"" ON ""SupplierWarehouseDebts"" (""SupplierId"", ""Warehouse"");

                ALTER TABLE ""ExportVouchers"" ADD COLUMN IF NOT EXISTS ""EmployeeId"" integer NULL;
                ALTER TABLE ""ExportVouchers"" ADD COLUMN IF NOT EXISTS ""EmployeeName"" character varying(200) NULL;
                ALTER TABLE ""ExportVouchers"" ADD COLUMN IF NOT EXISTS ""SupplierId"" integer NULL;
                ALTER TABLE ""ExportVouchers"" ADD COLUMN IF NOT EXISTS ""PartnerType"" character varying(20) NOT NULL DEFAULT 'customer';
                ALTER TABLE ""ExportVouchers"" ALTER COLUMN ""CustomerId"" DROP NOT NULL;

                ALTER TABLE ""ImportVouchers"" ADD COLUMN IF NOT EXISTS ""CustomerId"" integer NULL;
                ALTER TABLE ""ImportVouchers"" ADD COLUMN IF NOT EXISTS ""PartnerType"" character varying(20) NOT NULL DEFAULT 'supplier';
                ALTER TABLE ""ImportVouchers"" ALTER COLUMN ""SupplierId"" DROP NOT NULL;

                ALTER TABLE ""CustomerDebtHistories"" ADD COLUMN IF NOT EXISTS ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1';
                ALTER TABLE ""SupplierDebtHistories"" ADD COLUMN IF NOT EXISTS ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1';

                ALTER TABLE ""Payments"" ADD COLUMN IF NOT EXISTS ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1';
                ALTER TABLE ""Receipts"" ADD COLUMN IF NOT EXISTS ""Warehouse"" character varying(50) NOT NULL DEFAULT 'warehouse1';
            ");
        }
        else if (provider.Contains("Sqlite", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync(@"
                CREATE TABLE IF NOT EXISTS ""Employees"" (
                    ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_Employees"" PRIMARY KEY AUTOINCREMENT,
                    ""Name"" TEXT NOT NULL,
                    ""Phone"" TEXT NULL,
                    ""Notes"" TEXT NULL,
                    ""CreatedAt"" TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS ""CustomerWarehouseDebts"" (
                    ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_CustomerWarehouseDebts"" PRIMARY KEY AUTOINCREMENT,
                    ""CustomerId"" INTEGER NOT NULL,
                    ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1',
                    ""Debt"" TEXT NOT NULL DEFAULT '0',
                    ""UpdatedAt"" TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS ""SupplierWarehouseDebts"" (
                    ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_SupplierWarehouseDebts"" PRIMARY KEY AUTOINCREMENT,
                    ""SupplierId"" INTEGER NOT NULL,
                    ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1',
                    ""Debt"" TEXT NOT NULL DEFAULT '0',
                    ""UpdatedAt"" TEXT NOT NULL
                );
            ");
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ExportVouchers"" ADD COLUMN ""EmployeeId"" INTEGER NULL;"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ExportVouchers"" ADD COLUMN ""EmployeeName"" TEXT NULL;"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ExportVouchers"" ADD COLUMN ""SupplierId"" INTEGER NULL;"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ExportVouchers"" ADD COLUMN ""PartnerType"" TEXT NOT NULL DEFAULT 'customer';"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ImportVouchers"" ADD COLUMN ""CustomerId"" INTEGER NULL;"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ImportVouchers"" ADD COLUMN ""PartnerType"" TEXT NOT NULL DEFAULT 'supplier';"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""CustomerDebtHistories"" ADD COLUMN ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1';"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""SupplierDebtHistories"" ADD COLUMN ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1';"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Payments"" ADD COLUMN ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1';"); } catch { }
            try { await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Receipts"" ADD COLUMN ""Warehouse"" TEXT NOT NULL DEFAULT 'warehouse1';"); } catch { }
        }

        logger.LogInformation("Database is ready.");
    }
    catch (Exception ex)
    {
        logger.LogError(ex, "An error occurred while creating/migrating database.");
    }
}

// Global Exception Handling Middleware
app.UseMiddleware<DebtManager.Api.Middlewares.ExceptionHandlingMiddleware>();

// Enable Swagger in Development and Docker
app.UseSwagger();
app.UseSwaggerUI(c =>
{
    c.SwaggerEndpoint("/swagger/v1/swagger.json", "Debt Manager API v1");
    c.RoutePrefix = "swagger";
});

app.UseCors();

// Redirect root URL to swagger
app.MapGet("/", () => Results.Redirect("/swagger"));

app.UseAuthorization();

app.MapControllers();

app.Run();
